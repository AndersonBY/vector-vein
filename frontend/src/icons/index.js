// Keep presentation props and names already used by desktop components.
const createIcon = (name, Icon) => defineComponent({
  name,
  inheritAttrs: false,
  props: {
    size: { type: [Number, String], default: '1em' },
    theme: String,
    fill: [String, Array],
    spin: Boolean,
  },
  setup(props, { attrs }) {
    return () => h(Icon, {
      ...attrs,
      size: props.size,
      color: (Array.isArray(props.fill) ? props.fill[0] : props.fill) || 'currentColor',
      weight: props.theme === 'filled' ? 'fill' : props.theme === 'two-tone' ? 'duotone' : 'regular',
      class: ['vv-icon', attrs.class, props.spin && 'vv-icon-spin'],
    })
  },
})

